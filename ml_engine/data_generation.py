def _lower_first(text: str) -> str:
    return text[:1].lower() + text[1:]


def _compose(rng: random.Random, issue: str) -> str:
    ctx, time, opener = rng.choice(CONTEXTS), rng.choice(TIMES), rng.choice(OPENERS)
    pattern = rng.randrange(5)
    core = " ".join(part for part in (issue, ctx, time) if part)
    if pattern == 0:
        text = f"{core}."
    elif pattern == 1:
        text = f"{(ctx or 'Here').capitalize()}, {_lower_first(issue)} {time}".strip() + "."
    elif pattern == 2:
        text = f"{opener} {core}.".strip()
    elif pattern == 3:
        text = f"{core}. {opener}".strip()
    else:
        text = f"{core}, please fix it." if rng.random() < 0.5 else f"{core}, kindly resolve this."
    if rng.random() < 0.12:
        text = text.lower()
    if rng.random() < 0.08:
        text = text.rstrip(".")
    return " ".join(text.split())


def generate(per_class: int = 300, seed: int = 42, issues: dict | None = None, version: str = "synthetic_v1") -> list[dict]:
    """Default: the original four departments (synthetic_v1, unchanged). Pass issues=ALL_ISSUES, version="synthetic_v2" for all."""
    rng = random.Random(seed)
    rows = []
    for code, issues in (ISSUES if issues is None else issues).items():
        seen, attempts = set(), 0
        while len(seen) < per_class and attempts < per_class * 200:
            attempts += 1
            text = _compose(rng, rng.choice(issues))
            key = " ".join(text.lower().split())
            if key not in seen:
                seen.add(key)
                rows.append({"text": text, "department_code": code, "source": "SYNTHETIC",
                             "is_verified": "true", "dataset_version": version})
    rng.shuffle(rows)
    return rows


def write_csv(path: Path, rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=["text", "department_code", "source", "is_verified", "dataset_version"])
        writer.writeheader()
        writer.writerows(rows)
